CREATE TABLE pedidos_sala (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aula_id BIGINT NOT NULL,
    solicitante VARCHAR(255) NOT NULL,
    necessidade VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_pedidos_sala_aula FOREIGN KEY (aula_id) REFERENCES aulas (id)
);

CREATE INDEX idx_pedidos_sala_status ON pedidos_sala (status);
